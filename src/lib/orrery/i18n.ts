export type Copy = { [K in keyof (typeof copy)["zh"]]: string };
export const STRINGS: Record<Lang, Copy> = copy;

const PRESET_KEY = {
  dust: "dust",
  moon: "moon",
  planet: "planet",
  giant: "giant",
  star: "star",
} as const;

const SCENARIO_KEY = {
  system: "system",
  binary: "binary",
  eight: "eight",
  sling: "sling",
  triangle: "triangle",
  chaos: "chaos",
} as const;

export function presetLabel(lang: Lang, id: keyof typeof PRESET_KEY): string {
  return STRINGS[lang][PRESET_KEY[id]];
}

export function scenarioLabel(lang: Lang, id: keyof typeof SCENARIO_KEY): string {
  return STRINGS[lang][SCENARIO_KEY[id]];
}

export function scenarioTitle(lang: Lang, id: keyof typeof SCENARIO_KEY): string {
  const key = `${id}Title` as keyof Copy;
  return STRINGS[lang][key];
}

export function readLang(): Lang {
  try {
    const raw = localStorage.getItem("orrery-lang");
    if (raw && (LANGS as readonly string[]).includes(raw)) return raw as Lang;
  } catch {
    /* private mode */
  }
  return "zh";
}
